"""Generate pure C# event data and the Spanish tracking list; never generates artwork."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RARITIES = ('Común', 'Poco común', 'Raro', 'Épico', 'Legendario')
EFFECT_FIELDS = ('gold', 'heal', 'maxHp', 'luck', 'damage', 'upgrade', 'remove', 'card', 'relic')
CHOICE_FIELDS = ('goldCost', 'hpCost', 'maxHpCost', 'successPercent', 'setFlag', 'nextEventId', 'nextStage', 'isExit')

def value(v):
    if isinstance(v, bool): return str(v).lower()
    if isinstance(v, str): return json.dumps(v, ensure_ascii=False)
    return str(v)

def effect(data):
    args = [value(data['text'])]+[f'{k}: {value(data[k])}' for k in EFFECT_FIELDS if k in data]
    return 'new EventEffect('+', '.join(args)+')'

def option(data):
    args = [value(data['label']), effect(data['success'])]
    args += [f'{k}: {value(data[k])}' for k in CHOICE_FIELDS if k in data]
    if 'failure' in data: args.append('failure: '+effect(data['failure']))
    return 'new EventChoice('+', '.join(args)+')'

def detail(c):
    costs = [f'{c[k]} {label}' for k,label in [('goldCost','oro'),('hpCost','vida'),('maxHpCost','vida máxima')] if c.get(k)]
    text = c['label'] + (' ['+', '.join(costs)+']' if costs else '')
    if c.get('successPercent',100)<100: text += f" ({c['successPercent']}% éxito)"
    text += ': '+c['success']['text']
    if 'failure' in c: text += ' Fallo: '+c['failure']['text']
    if c.get('nextStage',-1)>=0: text += ' Abre otra decisión en esta sala.'
    return text.replace('|','/').replace('\n',' ')

def generate(root, check=False):
    events=json.loads((root/'docs/events-catalog.json').read_text(encoding='utf-8'))
    ids=[e['id'] for e in events]
    assert ids and len(ids)==len(set(ids)), 'Event IDs must be unique and the catalog must not be empty'
    flags={c.get('setFlag') for e in events for s in e['stages'] for c in s['choices'] if c.get('setFlag')}
    for e in events:
        assert 1<=e['rarity']<=5 and 1<=e['minFloor']<=e['maxFloor']
        assert not e['requiredFlag'] or e['requiredFlag'] in flags
        assert e['artStatus']=='Pendiente' and not e['artKey']
        for i,s in enumerate(e['stages']):
            assert any(c.get('isExit') for c in s['choices'])
            for c in s['choices']:
                assert not c.get('nextEventId') or c['nextEventId'] in ids
                assert c.get('nextStage',-1)==-1 or i<c['nextStage']<len(e['stages'])
                assert all(c.get(k,0)>=0 for k in ('goldCost','hpCost','maxHpCost'))
                assert 0<=c.get('successPercent',100)<=100
                assert c.get('successPercent',100)==100 or 'failure' in c
    cs=['// Generated by Tools/GenerateEvents.py from docs/events-catalog.json.',
        'using System;','using System.Collections.ObjectModel;','using System.Linq;',
        'namespace LastWish.Domain','{','    public static class EventCatalog','    {',
        '        public static readonly ReadOnlyCollection<EventDefinition> All = Array.AsReadOnly(new[]','        {']
    for e in events:
        args=[value(e[k]) for k in ('id','name','rarity','minFloor','maxFloor','requiredFlag')]
        cs.append('            new EventDefinition('+', '.join(args)+',')
        stages=[]
        for s in e['stages']:
            stages.append('                new EventStage('+value(s['body'])+',\n'+',\n'.join('                    '+option(c) for c in s['choices'])+')')
        cs.append(',\n'.join(stages)+'),')
    cs+=['        });','        public static EventDefinition Find(string id) => All.FirstOrDefault(e => e.Id == id);','    }','}']
    roots=[e for e in events if not e['requiredFlag'] and any(c.get('nextEventId') for s in e['stages'] for c in s['choices'])]
    staged=sum(len(e['stages'])>1 for e in events)
    md=['# Eventos de Last Wish — catálogo y seguimiento', '',
        f'{len(events)} eventos implementados en Unity. **Arte y diseño visual: pendientes en los {len(events)}**; no se generan imágenes ni efectos. '
        f'El catálogo incluye {len(roots)} historias enlazadas y {staged} encuentros de varias etapas.', '',
        'La fuente editable es `docs/events-catalog.json`. Ejecuta `python Tools/GenerateEvents.py` para regenerar el catálogo C# y esta lista; `--check` detecta desajustes. Python es solo una herramienta de edición: el juego ejecuta C# y no lee este JSON.', '',
        '## Reglas de aparición y resolución', '',
        '- Pisos 1, 2 y 3 tienen sucesos propios; también hay contenido exclusivo para 4–6, 7–9 y 10+, además de eventos generales y algunas historias que llegan hasta el piso 9.',
        '- Cada sala selecciona una rareza entre las disponibles con pesos 50/28/14/6/2 (Común/Poco común/Raro/Épico/Legendario), y luego un evento de esa rareza. Son pesos de categoría, no porcentajes por evento. La suerte no altera la aparición de sucesos.',
        '- Cada evento aparece una vez por partida. Si se agota el conjunto de eventos independientes del piso, se reutiliza Monedas entre las grietas para que siempre exista un encuentro.',
        f'- Las {len(roots)} historias enlazadas se desbloquean solo al aceptar la opción indicada. El próximo capítulo tiene prioridad en la siguiente sala de evento de un piso permitido; espera si aún estás demasiado arriba. Puede aparecer en el mismo piso si cumple su mínimo. Si rechazas continuar, no hay más capítulos. En los cuatro relatos con bifurcación, la elección central abre un solo final; el otro no puede aparecer.',
        '- No hay combate obligatorio ni cambios del mapa. Los eventos de varias etapas permiten entrar, decidir y comprar dentro de la misma sala. Salir siempre está disponible; una entrada ya pagada no se devuelve.',
        '- Los sacrificios de vida y vida máxima se validan antes de cobrar; siempre conservas al menos 1. La pérdida de vida máxima es permanente durante la partida y limita tu vida actual. El daño de un fallo tampoco mata.',
        '- Las cartas que se mejoran son la primera sin mejorar; las que se eliminan son la primera del mazo. Las opciones lo indican. No se elimina la última carta. Las cartas recibidas respetan la clase del héroe y el sistema de recompensas existente.',
        '- Las reliquias indicadas son las existentes, sin imágenes nuevas. No se permite comprar una que ya posees. Los precios de eventos son fijos: no usan descuentos, vales ni multiplicador de oro de Pruebas. Las ganancias sí pasan por el mecanismo normal de intereses.',
        '- Reabrir una sala conserva su sesión, decisiones y resultado. Cada elección se aplica una vez. Las salas usan semillas independientes; abrirlas no consume la aleatoriedad de combate, tienda o mapa.',
        '- `RunState.EventHistory` guarda por partida las decisiones, el piso, la sala y los resultados; `EventFlags` conserva las marcas de las cadenas. No añade guardado en disco (el juego actualmente no guarda partidas).', '',
        '## Lista de seguimiento', '',
        '| # | ID | Evento | Rareza | Pisos | Requiere | Enlaza con | Etapas | Programación | Diseño visual | Imagen |',
        '|---|---|---|---|---|---|---|---|---|---|---|']
    for i,e in enumerate(events,1):
        f=str(e['minFloor']) if e['minFloor']==e['maxFloor'] else f"{e['minFloor']}+" if e['maxFloor']==999999999 else f"{e['minFloor']}–{e['maxFloor']}"
        links=sorted({c['nextEventId'] for s in e['stages'] for c in s['choices'] if c.get('nextEventId')})
        md.append(f"| {i} | `{e['id']}` | {e['name']} | {RARITIES[e['rarity']-1]} | {f} | {e['requiredFlag'] or '—'} | {', '.join(links) or '—'} | {len(e['stages'])} | Implementada | Pendiente | Sin imagen |")
    # Show chain paths and alternate endings directly in the tracking list.
    by_id={e['id']:e for e in events}
    def story_paths(event_id, trail=()):
        assert event_id not in trail, 'Cycle in event links: '+event_id
        current=trail+(event_id,)
        links=[c['nextEventId'] for s in by_id[event_id]['stages'] for c in s['choices'] if c.get('nextEventId')]
        if not links: return [current]
        return [path for next_id in links for path in story_paths(next_id,current)]
    md+=['','## Historias enlazadas y finales alternativos','']
    for story in roots:
        paths=story_paths(story['id'])
        routes=[' → '.join('`'+event_id+'`' for event_id in path) for path in paths]
        md.append('- '+story['name']+': '+' / '.join(routes)+'.')
    md+=['','## Decisiones y consecuencias','']
    for i,e in enumerate(events,1):
        md += [f"### {i:02}. {e['name']} (`{e['id']}`)",'']
        for n,s in enumerate(e['stages'],1):
            md += [f"Etapa {n}: {s['body']}",'']
            for c in s['choices']:
                md.append('- '+detail(c)+(f" Marca: `{c['setFlag']}` → `{c['nextEventId']}`." if c.get('setFlag') else ''))
            md.append('')
    outputs={'Assets/Scripts/Domain/EventCatalog.Generated.cs':'\n'.join(cs)+'\n','docs/events.md':'\n'.join(md)+'\n'}
    for relative,content in outputs.items():
        path=root/relative
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=content: raise SystemExit('Outdated: '+relative)
        else:
            path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content,encoding='utf-8')
    print(f'{len(events)} events verified' if check else f'{len(events)} events generated')

if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); parser.add_argument('--root',type=Path,default=ROOT)
    args=parser.parse_args(); generate(args.root,args.check)
